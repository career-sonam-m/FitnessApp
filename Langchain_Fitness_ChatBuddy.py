def chat_with_agent(user_input=None):
    """
    Helper function to run single-turn interactions from terminal or script calls.

    Args:
        user_input (str | None): User prompt string. If None, prompts via input().

    Returns:
        str: Response string.
    """
    if user_input is None:
        user_input = input("You: ")

    # Initialize agent & chain using default environment settings
    _, calc, agent, chain = init_fitbuddy()
    session_id = "cli_default"
    return chat_with_fitbuddy(user_input, chain, session_id, None, calculator=calc, agent=agent)


def interactive_chat():
    """
    Runs an interactive terminal loop allowing real-time chat with FitBuddy.
    Exit using 'quit', 'exit', or 'q'.
    """
    print("=== FitBuddy AI Fitness Coach (CLI Mode) ===")
    print("Type 'quit', 'exit', or 'q' to end the conversation")
    print("-" * 45)

    while True:
        try:
            # Prompt user for input and strip surrounding whitespace
            user_input = input("\nYou: ").strip()
            
            # Check for exit commands
            if user_input.lower() in ['quit', 'exit', 'q']:
                print("Goodbye! Stay fit! 💪")
                break
                
            if not user_input:
                continue
                
            # Generate and print response
            response = chat_with_agent(user_input)
            print(f"\nFitBuddy: {response}")
            
        except KeyboardInterrupt:
            # Gracefully handle Ctrl+C interruption
            print("\nGoodbye! Stay fit! 💪")
            break
        except Exception as e:
            print(f"\nError encountered: {e}")


# Script entry point: runs interactive CLI chat when script is executed directly
if __name__ == "__main__":
    interactive_chat()
